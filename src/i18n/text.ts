const dictionaries: Record<AppLanguage, TextDictionary> = { es, en, zh };

export function translateText(language: AppLanguage, text: string): string {
  return dictionaries[language][text] ?? en[text] ?? text;
}

export function useAppText() {
  const language = useI18n((state) => state.language);
  return useCallback((text: string) => translateText(language, text), [language]);
}
